		if ((ZXDH_RING_USED_QUANTA(_ring) + (_count)) < size) {  \
			(_ring).head = ((_ring).head + (_count)) % size; \
			(_retcode) = 0;                                  \
		} else {                                                 \
			(_retcode) = -ENOSPC;                            \
		}                                                        \
